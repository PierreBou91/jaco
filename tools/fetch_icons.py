#!/usr/bin/env python3
"""Fetch Material Symbols Rounded (Apache 2.0) SVGs and convert them to Android vector drawables.

Usage: tools/fetch_icons.py   (writes app/src/main/res/drawable/ic_<name>[_fill].xml)
Add a name to ICONS and re-run to get a new icon. "name:fill" also fetches the filled variant.
"""
import re
import sys
import urllib.request
from pathlib import Path

ICONS = """
mic:fill stop:fill content_copy share delete download settings:fill deployed_code:fill expand_more close
chevron_right info wifi error refresh more_vert language graphic_eq timer speed memory arrow_back tune
pause play_arrow delete_sweep check check_circle:fill hard_drive star:fill bolt verified:fill
audio_file folder_open
""".split()

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{n}{v}_24px.svg"
OUT = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{n}"{fill_note} (Apache 2.0), generated by tools/fetch_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{d}" />
    </group>
</vector>
"""


def fetch(name: str, filled: bool) -> None:
    url = BASE.format(n=name, v="_fill1" if filled else "")
    svg = urllib.request.urlopen(url).read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        sys.exit(f"{name}: expected one path, got {len(paths)}")
    out = OUT / f"ic_{name}{'_fill' if filled else ''}.xml"
    out.write_text(TEMPLATE.format(n=name, fill_note=" filled" if filled else "", d=paths[0]))


for spec in ICONS:
    name, _, flag = spec.partition(":")
    fetch(name, False)
    if flag == "fill":
        fetch(name, True)
print(f"{len(list(OUT.glob('ic_*.xml')))} icons in {OUT}")
